/// Convert a FontStrategy preference string to the enum value.
FontStrategy pref_to_font_strategy(const std::string& value) {
    if (value == "render-missing") return FontStrategy::RENDER_MISSING;
    if (value == "substitute") return FontStrategy::SUBSTITUTE_MISSING;
    if (value == "keep-missing") return FontStrategy::KEEP_MISSING;
    if (value == "delete-missing") return FontStrategy::DELETE_MISSING;
    if (value == "render-all") return FontStrategy::RENDER_ALL;
    if (value == "delete-all") return FontStrategy::DELETE_ALL;
    qWarning("Unknown fontRendering option '%s'", value.c_str());
    return FontStrategy::SUBSTITUTE_MISSING;
}

