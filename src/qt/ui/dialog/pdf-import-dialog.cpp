void PdfImportDialog::onMeshSliderChanged(int value) {
    // Update the precision label
    int min = _ui->meshSlider->minimum();
    int max = _ui->meshSlider->maximum();
    int idx = static_cast<int>(std::floor((value - min) / static_cast<double>(max - min) * 4.0));
    idx = std::min(idx, 3);
    _ui->meshLabel->setText(tr(kPrecisionLabels[idx]));

    if (_mod) {
        _mod->set_param_float("approximationPrecision", static_cast<double>(value));
    }
}

