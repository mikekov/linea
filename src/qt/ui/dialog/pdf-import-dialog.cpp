FontStrategies PdfImportDialog::getFontStrategies() const {
    FontStrategies fs;
    if (!_fontModel) return fs;

    for (int row = 0; row < _fontModel->rowCount(); ++row) {
        int fontId = _fontModel->item(row, FontCol::COL_FONT_ID)->data(Qt::DisplayRole).toInt();
        int stratId = _fontModel->item(row, FontCol::COL_STRATEGY_ID)->data(Qt::DisplayRole).toInt();
        fs[fontId] = static_cast<FontFallback>(stratId);
    }
    return fs;
}

void PdfImportDialog::setFontStrategies(const FontStrategies& fs) {
    if (!_fontModel) return;

    for (int row = 0; row < _fontModel->rowCount(); ++row) {
        int fontId = _fontModel->item(row, FontCol::COL_FONT_ID)->data(Qt::DisplayRole).toInt();
        auto it = fs.find(fontId);
        if (it == fs.end()) continue;

        auto value = it->second;
        auto stratIdItem = _fontModel->item(row, FontCol::COL_STRATEGY_ID);
        if (!stratIdItem) continue;

        stratIdItem->setData(static_cast<int>(value), Qt::DisplayRole);

        // Update the combo box widget to reflect the strategy
        auto combo =
            qobject_cast<QComboBox*>(_ui->fontList->indexWidget(_fontModel->index(row, FontCol::COL_STRATEGY_LABEL)));
        if (combo) {
            QSignalBlocker blocker(combo);
            for (int i = 0; i < combo->count(); ++i) {
                if (combo->itemData(i).toInt() == static_cast<int>(value)) {
                    combo->setCurrentIndex(i);
                    break;
                }
            }
        }
    }
}

