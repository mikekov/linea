/// Populate a QComboBox from a list of entries, storing the ID string in Qt::UserRole.
void populate_combo(QComboBox* combo, const ComboEntry* entries, int count) {
    combo->clear();
    for (int i = 0; i < count; ++i) {
        combo->addItem(QObject::tr(entries[i].label), QString::fromUtf8(entries[i].id));
    }
}

/// Find the combo index whose UserRole data matches the given ID string.
int combo_index_by_id(QComboBox* combo, const std::string& id) {
    for (int i = 0; i < combo->count(); ++i) {
        if (combo->itemData(i, Qt::UserRole).toString().toStdString() == id) {
            return i;
        }
    }
    return 0;
}

/// Get the ID string for the currently selected combo item.
std::string combo_current_id(QComboBox* combo) {
    int idx = combo->currentIndex();
    if (idx < 0) return {};
    return combo->itemData(idx, Qt::UserRole).toString().toStdString();
}

