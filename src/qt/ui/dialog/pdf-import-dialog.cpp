void PdfImportDialog::setFonts(const FontList& fonts) {
    _fontModel->removeRows(0, _fontModel->rowCount());

    if (!fonts) return;

    for (auto& [font, data] : *fonts) {
        int row = _fontModel->rowCount();
        _fontModel->insertRow(row);

        // Icon column
        auto iconItem = new QStandardItem;
        if (font->isCIDFont()) {
            iconItem->setIcon(QIcon::fromTheme("text-convert-to-regular"));
        } else {
            iconItem->setIcon(QIcon::fromTheme(data.found ? "on" : "off-outline"));
        }
        _fontModel->setItem(row, FontCol::COL_ICON, iconItem);

        // Family
        auto familyItem = new QStandardItem;
        QString family = !data.family.empty() ? QString::fromStdString(data.family)
                                              : QString::fromStdString(data.name + " -> " + data.getSubstitute());
        familyItem->setText(family);
        _fontModel->setItem(row, FontCol::COL_FAMILY, familyItem);

        // Style, Weight, Stretch
        _fontModel->setItem(row, FontCol::COL_STYLE, new QStandardItem(QString::fromStdString(data.style)));
        _fontModel->setItem(row, FontCol::COL_WEIGHT, new QStandardItem(QString::fromStdString(data.weight)));
        _fontModel->setItem(row, FontCol::COL_STRETCH, new QStandardItem(QString::fromStdString(data.stretch)));

        // Strategy label item — empty text, the combo box is the visual
        auto stratLabelItem = new QStandardItem;
        stratLabelItem->setEditable(false);
        _fontModel->setItem(row, FontCol::COL_STRATEGY_LABEL, stratLabelItem);

        // Hidden: font ID
        auto fontIdItem = new QStandardItem;
        fontIdItem->setData(font->getID()->num, Qt::DisplayRole);
        _fontModel->setItem(row, FontCol::COL_FONT_ID, fontIdItem);

        // Hidden: strategy ID
        auto stratIdItem = new QStandardItem;
        stratIdItem->setData(0, Qt::DisplayRole);
        _fontModel->setItem(row, FontCol::COL_STRATEGY_ID, stratIdItem);

        // Install a per-row combo box for the strategy column
        auto combo = new QComboBox;
        combo->setSizePolicy(QSizePolicy::Expanding, QSizePolicy::Fixed);
        for (auto& e : kStrategyEntries) {
            combo->addItem(tr(e.label), e.id);
        }
        _ui->fontList->setIndexWidget(_fontModel->index(row, FontCol::COL_STRATEGY_LABEL), combo);

        // Connect combo change to update the hidden strategy ID
        QObject::connect(combo, qOverload<int>(&QComboBox::currentIndexChanged), this, [this, row](int comboIndex) {
            auto combo = qobject_cast<QComboBox*>(sender());
            if (!combo) return;
            int stratId = combo->itemData(comboIndex).toInt();
            auto stratIdItem = _fontModel->item(row, FontCol::COL_STRATEGY_ID);
            if (stratIdItem) stratIdItem->setData(stratId, Qt::DisplayRole);
        });
    }

    // Resize columns to contents
    _ui->fontList->resizeColumnToContents(FontCol::COL_ICON);
    _ui->fontList->resizeColumnToContents(FontCol::COL_STYLE);
    _ui->fontList->resizeColumnToContents(FontCol::COL_WEIGHT);
    _ui->fontList->resizeColumnToContents(FontCol::COL_STRETCH);
}

// ---- preview rendering ----

void PdfImportDialog::setPreviewPage(int page) {
    if (page < 1 || page > _totalPages) return;

    _previewPage = page;
    _ui->prevPage->setEnabled(page > 1);
    _ui->nextPage->setEnabled(page < _totalPages);
    _ui->currentPage->setText(QString("%1 / %2").arg(page).arg(_totalPages));

    renderPreview();
}

void PdfImportDialog::renderPreview() {
#ifndef HAVE_POPPLER_CAIRO
    // Use the PDF's embedded thumbnail
    if (_thumbData) {
        gfree(_thumbData);
        _thumbData = nullptr;
    }

    auto page = _pdfDoc->getCatalog()->getPage(_previewPage);
    if (!page) return;

    if (!page->loadThumb(&_thumbData, &_thumbWidth, &_thumbHeight, &_thumbRowstride)) {
        _ui->previewArea->setImage({});
        return;
    }

    // Convert raw RGB data to QImage
    QImage img(_thumbData, _thumbWidth, _thumbHeight, _thumbRowstride, QImage::Format_RGB888);
    _ui->previewArea->setPreviewSize(_thumbWidth, _thumbHeight + 20);
    _ui->previewArea->setImage(img.copy()); // deep copy so _thumbData can be freed later
    return;

#else
    // Render via poppler-glib + cairo, then convert to QImage (like PagesPanel does)
    if (!_popplerDoc) {
        _ui->previewArea->setImage({});
        return;
    }

    auto page = _pdfDoc->getCatalog()->getPage(_previewPage);
    if (!page) return;

    // Get page size, accounting for rotation
    double width, height;
    int rotate = page->getRotate();
    if (rotate == 90 || rotate == 270) {
        height = page->getCropWidth();
        width = page->getCropHeight();
    } else {
        width = page->getCropWidth();
        height = page->getCropHeight();
    }

    // Calculate scaling to fit the preview area
    double scale_x = static_cast<double>(_previewWidth) / width;
    double scale_y = static_cast<double>(_previewHeight) / height;
    double scale = std::min(scale_x, scale_y);

    int thumb_w = static_cast<int>(std::ceil(width * scale));
    int thumb_h = static_cast<int>(std::ceil(height * scale));

    // Check if we already have a cached surface for this page
    auto it = _cairoSurfaces.find(_previewPage);
    if (it != _cairoSurfaces.end() && it->second) {
        cairo_surface_t* surface = it->second.get();
        cairo_surface_flush(surface);
        QImage img = Inkscape::UI::cairo_surface_to_qimage(surface);
        if (!img.isNull()) {
            _ui->previewArea->setPreviewSize(thumb_w, thumb_h);
            _ui->previewArea->setImage(img);
        }
        return;
    }

    // Render asynchronously (like the original)
    if (_previewRenderingInProgress) return;
    _previewRenderingInProgress = true;

    auto cairo_surface = std::shared_ptr<cairo_surface_t>(
        cairo_image_surface_create(CAIRO_FORMAT_ARGB32, thumb_w, thumb_h), cairo_surface_destroy);

    auto poppler_page = Inkscape::Util::GObjectPtr(poppler_document_get_page(_popplerDoc, _previewPage - 1));

    auto [src, dst] = Inkscape::Async::Channel::create();

    Inkscape::Async::fire_and_forget([cairo_surface, scale, poppler_page = std::move(poppler_page),
                                      channel = std::move(src), dialog = this, page = _previewPage]() mutable {
        cairo_t* cr = cairo_create(cairo_surface.get());
        cairo_set_source_rgba(cr, 1.0, 1.0, 1.0, 1.0);
        cairo_paint(cr);
        cairo_scale(cr, scale, scale);
        poppler_page_render(poppler_page.get(), cr);
        cairo_destroy(cr);

        channel.run([dialog, page] {
            dialog->_previewRenderingInProgress = false;
            if (dialog->_previewPage == page) {
                dialog->renderPreview();
            }
        });
    });

    _channels.push_back(std::move(dst));
    _cairoSurfaces[_previewPage] = std::move(cairo_surface);

    _ui->previewArea->setPreviewSize(thumb_w, thumb_h);
#endif
}

