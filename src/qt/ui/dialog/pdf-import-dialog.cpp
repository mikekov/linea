    QString full_uri = QUrl::fromLocalFile(QString::fromStdString(filename)).toString();
    if (!full_uri.isEmpty()) {
        _popplerDoc = poppler_document_new_from_file(full_uri.toUtf8().constData(), nullptr, nullptr);
    }
#else
    _totalPages = _pdfDoc->getCatalog()->getNumPages();
#endif

