// Convert Cairo surface to QPixmap
QPixmap surfaceToPixmap(const Cairo::RefPtr<Cairo::Surface>& surface, int width, int height) {
    if (!surface) return {};

    auto image = Cairo::ImageSurface::create(Cairo::Surface::Format::ARGB32, width, height);
    auto ctx = Cairo::Context::create(image);
    ctx->set_source(surface, 0, 0);
    ctx->paint();
    image->flush();

    // Cairo ARGB32 is premultiplied; copy to detach from the Cairo buffer.
    QImage qimage(image->get_data(), width, height, image->get_stride(), QImage::Format_ARGB32_Premultiplied);
    QImage copy = qimage.copy();
    return QPixmap::fromImage(copy);
}

// Draw gradient to Cairo surface
void drawGradient(SPGradient* gr, int width, int height, cairo_t* ct) {
    if (!gr) return;

    auto check = ink_cairo_pattern_create_checkerboard();
    cairo_set_source(ct, check->cobj());
    cairo_paint(ct);

    auto p = gr->create_preview_pattern(width);
    if (!p) return;
    cairo_set_source(ct, p);
    cairo_paint(ct);
    cairo_pattern_destroy(p);
}

// Convert gradient to QPixmap
QPixmap gradientToPixmap(SPGradient* gr, int width, int height) {
    cairo_surface_t* s = cairo_image_surface_create(CAIRO_FORMAT_ARGB32, width, height);
    cairo_t* ct = cairo_create(s);
    drawGradient(gr, width, height, ct);
    cairo_destroy(ct);
    cairo_surface_flush(s);

    auto surface = Cairo::RefPtr<Cairo::Surface>(new Cairo::Surface(s, true));
    QPixmap result = surfaceToPixmap(surface, width, height);
    return result;
}

// Return a "HHSSLL" version of the first stop color for sorting
unsigned long gradientToHhssll(SPGradient* gr) {
    if (!gr || !gr->getFirstStop()) return 0;
    auto hsl = gr->getFirstStop()->getColor();
    hsl.convert(Inkscape::Colors::Space::Type::HSL);
    return (static_cast<unsigned long>(hsl[0] * 100 * 10000) +
            static_cast<unsigned long>(hsl[1] * 100 * 100) +
            static_cast<unsigned long>(hsl[2] * 100));
}

// Prepare label for gradient
QString prepareLabel(SPObject* obj) {
    const gchar* id = obj->label() ? obj->label() : obj->getId();
    if (!id) {
        id = obj->getRepr()->name();
    }

    QString label = QString::fromUtf8(id);
    if (label.length() > 14 && (label.startsWith("linearGradient") || label.startsWith("radialGradient"))) {
        return label.mid(14);
    }
    return label;
}

// Ellipsize text if longer than maxlen
QString ellipsizeText(const QString& src, size_t maxlen) {
    if (src.length() > static_cast<int>(maxlen) && maxlen > 8) {
        size_t p1 = maxlen / 2;
        size_t p2 = src.length() - (maxlen - p1 - 1);
        return src.mid(0, static_cast<int>(p1)) + "\u2026" + src.mid(static_cast<int>(p2));
    }
    return src;
}

