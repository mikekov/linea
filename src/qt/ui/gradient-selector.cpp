void GradientSelector::updateTable() {
    QSignalBlocker blocker(_ui->gradientTable);

    _ui->gradientTable->clearContents();
    _ui->gradientTable->setRowCount(0);
    _gradients.clear();
    _usageCounts.clear();

    if (!_doc) {
        _ui->gradientTable->setRowCount(1);
        auto* item = new QTableWidgetItem(tr("No document selected"));
        _ui->gradientTable->setItem(0, 1, item);
        return;
    }

    if (!_gradient) {
        _ui->gradientTable->setRowCount(1);
        auto* item = new QTableWidgetItem(tr("No gradient selected"));
        _ui->gradientTable->setItem(0, 1, item);
        return;
    }

    // Collect gradients
    auto resources = _gradient->document->getResourceList("gradient");
    for (auto* obj : resources) {
        auto* gr = cast<SPGradient>(obj);
        if (gr && gr->hasStops() && gr->isSwatch() == (_mode == MODE_SWATCH)) {
            _gradients.push_back(gr);
        }
    }

    if (_gradients.empty()) {
        _ui->gradientTable->setRowCount(1);
        auto* item = new QTableWidgetItem(tr("No gradients in document"));
        _ui->gradientTable->setItem(0, 1, item);
        return;
    }

    // Calculate usage counts
    for (auto* obj : _doc->getRoot()) {
        auto* item = cast<SPItem>(obj);
        if (!item || !item->getId()) continue;

        SPGradient* gr = sp_item_get_gradient(item, true);  // fill
        if (gr) {
            _usageCounts[gr]++;
        }
        gr = sp_item_get_gradient(item, false);  // stroke
        if (gr) {
            _usageCounts[gr]++;
        }
    }

    // Sort gradients based on current sort column
    if (_sortColumn == 0) {
        // Sort by color (hhssll)
        std::sort(_gradients.begin(), _gradients.end(),
            [this](SPGradient* a, SPGradient* b) {
                bool less = gradientToHhssll(a) < gradientToHhssll(b);
                return _sortOrder == Qt::AscendingOrder ? less : !less;
            });
    } else if (_sortColumn == 1) {
        // Sort by name
        std::sort(_gradients.begin(), _gradients.end(),
            [this](SPGradient* a, SPGradient* b) {
                bool less = prepareLabel(a) < prepareLabel(b);
                return _sortOrder == Qt::AscendingOrder ? less : !less;
            });
    } else if (_sortColumn == 2) {
        // Sort by refcount
        std::sort(_gradients.begin(), _gradients.end(),
            [this](SPGradient* a, SPGradient* b) {
                bool less = _usageCounts[a] < _usageCounts[b];
                return _sortOrder == Qt::AscendingOrder ? less : !less;
            });
    }

    // Populate table
    _ui->gradientTable->setRowCount(static_cast<int>(_gradients.size()));

    for (size_t i = 0; i < _gradients.size(); ++i) {
        auto* gr = _gradients[i];
        int row = static_cast<int>(i);

        // Gradient icon
        QPixmap pixmap = gradientToPixmap(gr, _pixWidth, _pixHeight);
        auto* iconItem = new QTableWidgetItem();
        iconItem->setData(Qt::DecorationRole, pixmap);
        iconItem->setData(Qt::UserRole, QVariant::fromValue(static_cast<void*>(gr)));
        iconItem->setFlags(iconItem->flags() & ~Qt::ItemIsEditable);
        _ui->gradientTable->setItem(row, 0, iconItem);

        // Name
        QString label = ellipsizeText(prepareLabel(gr), 35);
        auto* nameItem = new QTableWidgetItem(label);
        nameItem->setData(Qt::UserRole, QVariant::fromValue(static_cast<void*>(gr)));
        nameItem->setFlags(nameItem->flags() | Qt::ItemIsEditable);
        _ui->gradientTable->setItem(row, 1, nameItem);

        // Refcount
        int count = _usageCounts[gr];
        auto* countItem = new QTableWidgetItem(QString::number(count));
        countItem->setData(Qt::UserRole, QVariant::fromValue(static_cast<void*>(gr)));
        countItem->setFlags(countItem->flags() & ~Qt::ItemIsEditable);
        _ui->gradientTable->setItem(row, 2, countItem);
    }
}

void GradientSelector::selectGradientInTable(SPGradient* vector) {
    if (!vector) return;

    QSignalBlocker blocker(_ui->gradientTable);
    for (int row = 0; row < _ui->gradientTable->rowCount(); ++row) {
        auto* item = _ui->gradientTable->item(row, 0);
        if (!item) continue;

        auto* gr = static_cast<SPGradient*>(item->data(Qt::UserRole).value<void*>());
        if (gr == vector) {
            _ui->gradientTable->selectRow(row);
            _ui->gradientTable->scrollToItem(item, QAbstractItemView::PositionAtCenter);
            break;
        }
    }
}

void GradientSelector::onTableSelectionChanged() {
    if (_blocked) return;

    auto selected = _ui->gradientTable->selectedItems();
    if (selected.isEmpty()) return;

    auto* item = selected.first();
    auto* gr = static_cast<SPGradient*>(item->data(Qt::UserRole).value<void*>());

    if (gr) {
        vectorSet(gr);
    }

    checkDeleteButton();
}

void GradientSelector::onTableCellChanged(int row, int column) {
    if (column != 1) return;  // Only handle name changes

    auto* item = _ui->gradientTable->item(row, column);
    if (!item) return;

    auto* gr = static_cast<SPGradient*>(item->data(Qt::UserRole).value<void*>());
    if (!gr) return;

    QString newText = item->text();
    QString currentLabel = prepareLabel(gr);

    if (!newText.isEmpty() && newText != currentLabel) {
        gr->setLabel(newText.toUtf8().constData());
        DocumentUndo::done(gr->document, RC_("Undo", "Rename gradient"), INKSCAPE_ICON("color-gradient"));
        item->setText(ellipsizeText(prepareLabel(gr), 35));
    }
}

void GradientSelector::onNameHeaderClicked() {
    if (_sortColumn == 1) {
        _sortOrder = (_sortOrder == Qt::AscendingOrder) ? Qt::DescendingOrder : Qt::AscendingOrder;
    } else {
        _sortColumn = 1;
        _sortOrder = Qt::AscendingOrder;
    }
    updateTable();
}

void GradientSelector::onColorHeaderClicked() {
    if (_sortColumn == 0) {
        _sortOrder = (_sortOrder == Qt::AscendingOrder) ? Qt::DescendingOrder : Qt::AscendingOrder;
    } else {
        _sortColumn = 0;
        _sortOrder = Qt::AscendingOrder;
    }
    updateTable();
}

void GradientSelector::onCountHeaderClicked() {
    if (_sortColumn == 2) {
        _sortOrder = (_sortOrder == Qt::AscendingOrder) ? Qt::DescendingOrder : Qt::AscendingOrder;
    } else {
        _sortColumn = 2;
        _sortOrder = Qt::AscendingOrder;
    }
    updateTable();
}

void GradientSelector::checkDeleteButton() {
    auto selected = _ui->gradientTable->selectedItems();
    if (selected.isEmpty()) {
        _ui->del2Button->setEnabled(false);
        return;
    }

    auto* item = selected.first();
    auto* gr = static_cast<SPGradient*>(item->data(Qt::UserRole).value<void*>());

    if (!gr || !_doc) {
        _ui->del2Button->setEnabled(false);
        return;
    }

    int count = _usageCounts[gr];
    bool canDelete = count < 2 && _gradients.size() > 1;
    _ui->del2Button->setEnabled(canDelete);
}

void GradientSelector::vectorSet(SPGradient* gr) {
    if (_blocked) return;

    _blocked = true;
    gr = sp_gradient_ensure_vector_normalized(gr);
    setVector(gr ? gr->document : nullptr, gr);
    Q_EMIT signalChanged(gr);
    _blocked = false;
}

void GradientSelector::moveSelection(int amount, bool down, bool toEnd) {
    auto selected = _ui->gradientTable->selectedItems();
    if (selected.isEmpty()) return;

    int currentRow = selected.first()->row();
    int newRow = currentRow;

    if (toEnd) {
        newRow = down ? _ui->gradientTable->rowCount() - 1 : 0;
    } else {
        newRow = down ? currentRow + amount : currentRow - amount;
    }

    newRow = std::clamp(newRow, 0, _ui->gradientTable->rowCount() - 1);

    if (newRow != currentRow) {
        _ui->gradientTable->selectRow(newRow);
        _ui->gradientTable->scrollToItem(_ui->gradientTable->item(newRow, 0), QAbstractItemView::PositionAtCenter);
    }
}

void GradientSelector::onKeyPressed(int key) {
    switch (key) {
        case Qt::Key_Up:
        case Qt::Key_K:
            moveSelection(1, false);
            break;
        case Qt::Key_Down:
        case Qt::Key_J:
            moveSelection(1, true);
            break;
        case Qt::Key_PageUp:
            moveSelection(5, false);
            break;
        case Qt::Key_PageDown:
            moveSelection(5, true);
            break;
        case Qt::Key_Home:
            moveSelection(0, false, true);
            break;
        case Qt::Key_End:
            moveSelection(0, true, true);
            break;
    }
}

void GradientSelector::onAddClicked() {
    if (!_doc) return;

    auto* gr = _gradient;
    auto* xmlDoc = _doc->getReprDoc();

    Inkscape::XML::Node* repr = nullptr;

    if (gr) {
        gr->getRepr()->removeAttribute("inkscape:collect");
        repr = gr->getRepr()->duplicate(xmlDoc);
        auto newId = generate_similar_unique_id(_doc, gr->getId());
        gr->setAttribute("id", newId.c_str());
        _doc->getDefs()->getRepr()->appendChild(repr);
    } else {
        repr = xmlDoc->createElement("svg:linearGradient");
        auto* stop = xmlDoc->createElement("svg:stop");
        stop->setAttribute("offset", "0");
        stop->setAttribute("style", "stop-color:#000;stop-opacity:1;");
        repr->appendChild(stop);
        Inkscape::GC::release(stop);

        stop = xmlDoc->createElement("svg:stop");
        stop->setAttribute("offset", "1");
        stop->setAttribute("style", "stop-color:#fff;stop-opacity:1;");
        repr->appendChild(stop);
        Inkscape::GC::release(stop);

        _doc->getDefs()->getRepr()->appendChild(repr);
        gr = cast<SPGradient>(_doc->getObjectByRepr(repr));
    }

    setVector(_doc, gr);
    selectGradientInTable(gr);
    vectorSet(gr);

    Inkscape::GC::release(repr);
}

void GradientSelector::onDeleteClicked() {
    auto selected = _ui->gradientTable->selectedItems();
    if (selected.isEmpty()) return;

    auto* item = selected.first();
    auto* gr = static_cast<SPGradient*>(item->data(Qt::UserRole).value<void*>());

    if (gr) {
        std::string id = gr->getId();
        sp_gradient_unset_swatch(SP_ACTIVE_DESKTOP, id);
    }
}

void GradientSelector::onDeleteUnusedClicked() {
    auto selected = _ui->gradientTable->selectedItems();
    if (selected.isEmpty()) return;

    auto* item = selected.first();
    auto* gr = static_cast<SPGradient*>(item->data(Qt::UserRole).value<void*>());

    if (!gr) return;

    auto* repr = gr->getRepr();
    if (!repr) return;

    repr->setAttribute("inkscape:collect", "always");

    // Select next or previous row
    int row = item->row();
    int newRow = row - 1;
    if (newRow < 0) {
        newRow = row + 1;
    }

    if (newRow >= 0 && newRow < _ui->gradientTable->rowCount()) {
        _ui->gradientTable->selectRow(newRow);
        _ui->gradientTable->scrollToItem(_ui->gradientTable->item(newRow, 0), QAbstractItemView::PositionAtCenter);
    }
}

void GradientSelector::onEditClicked() {
    // Invoke the gradient tool - button is typically hidden
    set_active_tool(SP_ACTIVE_DESKTOP, "Gradient");
}

