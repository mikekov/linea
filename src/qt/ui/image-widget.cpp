QPixmap draw_preview(const Inkscape::Pixbuf* image, double alpha, int width, int height, double device_scale,
                     const QColor& background) {
    if (!image) return {};

    QImage src = Inkscape::UI::cairo_surface_to_qimage(image->getSurfaceRaw());
    if (src.isNull()) return {};

    // minify to fit within width x height, preserving aspect ratio (smooth bilinear)
    src = src.scaled(width * device_scale, height * device_scale, Qt::KeepAspectRatio, Qt::FastTransformation);
    src.setDevicePixelRatio(device_scale);

    QImage out(src.size(), QImage::Format_ARGB32_Premultiplied);
    out.setDevicePixelRatio(device_scale);
    out.fill(Qt::transparent);

    QPainter p(&out);
    // checkerboard shows through where the image is not fully opaque
    if (alpha < 1.0) {
        p.setBrushOrigin(out.rect().topLeft());
        p.fillRect(out.rect(), QBrush(checkerPattern(background)));
    }
    p.setOpacity(alpha);
    p.drawImage(0, 0, src);
    p.end();

    return QPixmap::fromImage(out);
}

// Save 'pixbuf' image into a file. The format is inferred from the filename
// extension by Qt's image writer (Qt replacement for gdk_pixbuf_save).
bool save_png(const QString& fname, const Inkscape::Pixbuf* pixbuf) {
    if (fname.isEmpty() || !pixbuf) return false;

    Inkscape::Pixbuf image(*pixbuf);
    // Cairo stores premultiplied ARGB32, which maps onto QImage directly.
    image.ensurePixelFormat(Inkscape::Pixbuf::PF_CAIRO);

    // QImage wraps the buffer without copying; 'image' outlives the save() call.
    QImage qimage(image.pixels(), image.width(), image.height(), image.rowstride(),
                  QImage::Format_ARGB32_Premultiplied);
    return qimage.save(fname);
}

void populate_icon_combobox(IconComboBox* combo, const SPStyleEnum* table, const QMap<int, QString>& labels) {
    if (!combo || !table) return;
    for (int i = 0; table[i].key; ++i) {
        const auto& e = table[i];
        auto label = labels.value(e.value, QString::fromUtf8(e.key));
        combo->addRow(QString(), label, label, e.value);
    }
}

