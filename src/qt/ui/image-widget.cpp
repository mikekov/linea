void ImageWidget::onChangeImage() {
    if (_update.pending() || !_image) return;

    QString file =
        QFileDialog::getOpenFileName(this, tr("Change Image"), QString(),
                                     tr("Images (*.png *.jpg *.jpeg *.gif *.bmp *.tif *.tiff *.svg);;All Files (*)"));
    if (file.isEmpty()) return;

    char* uri = g_filename_to_uri(file.toUtf8().constData(), nullptr, nullptr);
    if (!uri) return;
    Inkscape::setHrefAttribute(*_image->getRepr(), uri);
    g_free(uri);

    // SPImage modifies size when href changes; trigger it now before undo concludes
    _image->document->_updateDocument(0);
    DocumentUndo::done(_image->document, RC_("Undo", "Change image"), INKSCAPE_ICON("shape-image"));

    resetPreview();
    // todo
    //  update(_image);
}

void ImageWidget::onExportImage() {
    if (_update.pending() || !_image || !_image->pixbuf) return;

    QString file =
        QFileDialog::getSaveFileName(this, tr("Extract Image"), QStringLiteral("image.png"), tr("PNG Image (*.png)"));
    if (file.isEmpty()) return;

    save_png(file, _image->pixbuf.get());
}

void ImageWidget::onEmbed() {
    if (_update.pending() || !_image || !_image->pixbuf) return;

    // embed image in the current document
    Inkscape::Pixbuf copy(*_image->pixbuf);
    sp_embed_image(_image->getRepr(), &copy);
    DocumentUndo::done(_image->document, RC_("Undo", "Embed image"), INKSCAPE_ICON("selection-make-bitmap-copy"));
}

void ImageWidget::onTrace() {
    if (!_image || !_image->pixbuf) return;

    // Build a BitmapView from the pixbuf's cairo surface (ARGB32 premultiplied).
    const auto* pb = _image->pixbuf.get();
    Inkscape::Trace::BitmapView bmp{pb->width(), pb->height(), pb->rowstride(), pb->pixels()};

    // Lazily create the trace panel (reused across popups).
    if (!_tracePanel) {
        _tracePanel = new TracePanel(this);
        connect(_tracePanel, &TracePanel::traceRequested, this, [this] {
            _traceFuture.cancel();
            auto engine = _tracePanel->takeEngine();
            _traceFuture = Inkscape::Trace::trace(
                std::move(engine), _tracePanel->sioxEnabled(),
                [this](double frac) { _tracePanel->setTraceProgress(frac); },
                [this] { _tracePanel->setTraceComplete(); });
        });
        connect(_tracePanel, &TracePanel::previewRequested, this, [this] {
            _previewFuture.cancel();
            auto engine = _tracePanel->takeEngine();
            _previewFuture = Inkscape::Trace::preview(std::move(engine), _tracePanel->sioxEnabled(),
                                                      [this](QImage img) { _tracePanel->setPreview(std::move(img)); });
        });
        connect(_tracePanel, &TracePanel::traceAborted, this, [this] { _traceFuture.cancel(); });
    }
    _tracePanel->setImage(bmp);

    auto popup = new Linea::UI::PopupMenu(this);
    popup->setContent(_tracePanel);
    popup->showLeftOfWidget(_ui->traceBtn);
}

