ImageWidget::ImageWidget(QWidget* parent)
    : QWidget(parent)
    , _ui(std::make_unique<Ui::ImageWidget>()) {
    _ui->setupUi(this);

    _ui->dpiEdit->setRange(1.0, 2400.0);
    _ui->dpiEdit->setDecimals(4);
    _ui->dpiEdit->setValue(96.0);

    const QMap<int, QString> renderingLabels = {
        {SP_CSS_IMAGE_RENDERING_AUTO, tr("Automatic")},
        {SP_CSS_IMAGE_RENDERING_OPTIMIZESPEED, tr("Optimize speed")},
        {SP_CSS_IMAGE_RENDERING_OPTIMIZEQUALITY, tr("Optimize quality")},
        {SP_CSS_IMAGE_RENDERING_CRISPEDGES, tr("Crisp edges")},
        {SP_CSS_IMAGE_RENDERING_PIXELATED, tr("Pixelated")},
    };
    populate_icon_combobox(_ui->renderingCombo, enum_image_rendering, renderingLabels);

    connect(_ui->changeButton, &QPushButton::clicked, this, &ImageWidget::onChangeImage);
    connect(_ui->exportButton, &QPushButton::clicked, this, &ImageWidget::onExportImage);
    connect(_ui->embedButton, &QPushButton::clicked, this, &ImageWidget::onEmbed);
    connect(_ui->traceBtn, &QPushButton::clicked, this, &ImageWidget::onTrace);
}

ImageWidget::~ImageWidget() = default;

void ImageWidget::bind(Linea::Props::Binder& binder) {
    _desktop = binder.editor()->desktop();

    _ui->renderingCombo->setHeaderType(IconComboBox::LabelOnly);

    binder.bind(Linea::Props::image_url, _ui->hrefEdit);
    binder.bind(Linea::Props::image_dpi, _ui->dpiEdit);
    binder.bind(Linea::Props::image_preserve_aspect, _ui->aspectGroup);
    binder.bind(Linea::Props::image_rendering, _ui->renderingCombo);

    auto updateInfo = [this](const Linea::Props::SelectionState& s) {
        const auto& e = s.element;
        if (e.image_dimensions.is_mixed() || e.image_embedded.is_mixed() || e.image_linked.is_mixed() ||
            e.image_color_space.is_mixed() || e.image_missing.is_mixed()) {
            _ui->infoLabel->setText("-");
            return;
        }

        if (e.image_missing.is_single() && e.image_missing.value()) {
            _ui->infoLabel->setText(_("Missing image"));
            return;
        }

        std::ostringstream ost;
        if (e.image_dimensions.is_single()) {
            const auto& [w, h] = e.image_dimensions.value();
            auto times = "\u00d7"; // multiplication sign
            ost << w << times << h << " px\n";
        }

        if (e.image_embedded.is_single() && e.image_embedded.value()) {
            ost << _("Embedded");
            if (e.image_data_size.is_single()) {
                ost << " (" << Inkscape::Util::format_file_size(e.image_data_size.value()) << ")";
            }
            ost << '\n';
        } else if (e.image_linked.is_single() && e.image_linked.value()) {
            ost << _("Linked") << '\n';
        }

        if (e.image_color_space.is_single() && !e.image_color_space.value().empty()) {
            ost << _("Color profile:") << ' ' << e.image_color_space.value() << '\n';
        }

        _ui->infoLabel->setText(QString::fromUtf8(ost.str().c_str()));
    };

    binder.bindField(Linea::Props::Field::image_dimensions, updateInfo);
    binder.bindField(Linea::Props::Field::image_embedded, updateInfo);
    binder.bindField(Linea::Props::Field::image_linked, updateInfo);
    binder.bindField(Linea::Props::Field::image_color_space, updateInfo);
    binder.bindField(Linea::Props::Field::image_missing, updateInfo);
    binder.bindField(Linea::Props::Field::image_data_size, updateInfo);

    auto updateUrlEnable = [this](const Linea::Props::SelectionState& s) {
        const auto& e = s.element;
        _ui->hrefEdit->setEnabled(e.image_embedded.is_single() && !e.image_embedded.value());
    };
    binder.bindField(Linea::Props::Field::image_embedded, updateUrlEnable);

    binder.bindField(Linea::Props::Field::image_pixbuf, [this](const Linea::Props::SelectionState&) {
        if (!_desktop) return;
        auto sel = _desktop->getSelection();
        setImage(sel ? dynamic_cast<SPImage*>(sel->single()) : nullptr);
    });
    binder.bindField(Linea::Props::Field::opacity, [this](const Linea::Props::SelectionState& s) {
        if (!_image || !_image->style) return;
        update(_image->pixbuf, _image->style->opacity.as_double());
    });

    // only show image properties when all selected items are images
    binder.visibleWhen(this, Linea::Props::Cond::allOf<&Linea::Props::Counts::images>);
}

void ImageWidget::setImage(SPImage* image) {
    if (image == _image) return;

    _image = image;
    auto opacity = image && image->style ? image->style->opacity.as_double() : 1.0;
    update(image ? image->pixbuf : nullptr, opacity);
}

void ImageWidget::update(std::shared_ptr<const Inkscape::Pixbuf> pixbuf, double opacity) {
    if (pixbuf != _pixbuf || _imageOpacity != opacity) {
        _pixbuf = pixbuf;
        _imageOpacity = opacity;
        resetPreview();
    }
    rebuildPreview();
}

void ImageWidget::resetPreview() {
    _hasPreview = false;
    _ui->previewLabel->setPixmap(QPixmap());
}

void ImageWidget::rebuildPreview() {
    if (_hasPreview) return;

    int width = _ui->previewLabel->width();
    int height = _ui->previewLabel->height();

    double device_scale = devicePixelRatioF();
    auto base = palette().base().color();
    _ui->previewLabel->setPixmap(draw_preview(_pixbuf.get(), _imageOpacity, width, height, device_scale, base));
    _hasPreview = true;
}

