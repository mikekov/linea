ExportWidget::ExportWidget(QWidget* parent)
    : QWidget(parent)
    , _ui(std::make_unique<Ui::ExportWidget>())
{
    _ui->setupUi(this);
    updateExportButtonVisibility();

    _ui->titleLabel->setCursor(Qt::PointingHandCursor);
    _ui->titleLabel->installEventFilter(this);
    connect(_ui->addExportButton, &QPushButton::clicked, this, &ExportWidget::addSingleExport);

    connect(_ui->exportButton, &QPushButton::clicked, this, [this] {
        std::vector<Linea::IO::ExportJob> jobs;
        for (int i = 0; i < _ui->exportTasksLayout->count(); ++i) {
            auto task = static_cast<SingleExport*>(_ui->exportTasksLayout->itemAt(i)->widget());
            if (auto extension = task->selectedExtension()) {
                jobs.push_back({extension, task->dpi()});
            }
        }
        auto exported = Linea::IO::exportSelection(_desktop, jobs);
        if (!exported.empty()) {
            revealInFileManager(QString::fromStdString(exported.front()));
        }
    });
}

bool ExportWidget::eventFilter(QObject* watched, QEvent* event) {
    if (watched == _ui->titleLabel && event->type() == QEvent::MouseButtonRelease) {
        auto mouseEvent = static_cast<QMouseEvent*>(event);
        if (mouseEvent->button() == Qt::LeftButton) {
            addSingleExport();
            return true;
        }
    }
    return QWidget::eventFilter(watched, event);
}

ExportWidget::~ExportWidget() = default;

void ExportWidget::addSingleExport() {
    auto task = new SingleExport(_ui->exportTasksContainer);
    task->setRemoveHandler([this, task] { removeSingleExport(task); });
    _ui->exportTasksLayout->addWidget(task);
    updateExportButtonVisibility();
}

void ExportWidget::removeSingleExport(QWidget* task) {
    if (!task) {
        return;
    }

    _ui->exportTasksLayout->removeWidget(task);
    task->deleteLater();
    updateExportButtonVisibility();
}

void ExportWidget::updateExportButtonVisibility() {
    _ui->exportButton->setVisible(_ui->exportTasksLayout->count() > 0);
}

void ExportWidget::bind(Props::Binder& binder) {
    _desktop = binder.editor()->desktop();
    binder.visibleWhen(this, Props::Cond::hasSelection || Props::Cond::hasPageSelection);
}

