// Show the exported file in the platform's file browser. All exports share
// one directory, so revealing a single file shows them all.
void revealInFileManager(const QString& path) {
#ifdef __APPLE__
    // open in Finder and select the file
    QProcess::startDetached(QStringLiteral("open"), {QStringLiteral("-R"), path});
#elif defined(_WIN32)
    QProcess::startDetached(QStringLiteral("explorer"), {QStringLiteral("/select,") + QDir::toNativeSeparators(path)});
#else
    QDesktopServices::openUrl(QUrl::fromLocalFile(QFileInfo(path).absolutePath()));
#endif
}


class SingleExport final : public QWidget {
public:
    explicit SingleExport(QWidget* parent = nullptr)
        : QWidget(parent)
    {
        auto prefs = Inkscape::Preferences::get();
        constexpr auto dpi_pref = "/dialogs/export/defaultxdpi/value";

        auto layout = new QGridLayout(this);
        layout->setContentsMargins(0, 0, 0, 0);
        layout->setSpacing(4);
        layout->setColumnStretch(0, 1);
        layout->setColumnStretch(1, 1);
        layout->setColumnStretch(2, 0);
        layout->setColumnStretch(3, 0);

        auto dpiSelector = new IconComboBox(this);
        dpiSelector->setToolTip(tr("Choose image resolution"));
        dpiSelector->addRow(QString(), tr("×1"), 96);
        dpiSelector->addRow(QString(), tr("×2"), 192);
        dpiSelector->addRow(QString(), tr("300 DPI"), 300);
        dpiSelector->addRow(QString(), tr("600 DPI"), 600);
        dpiSelector->addRow(QString(), tr("1200 DPI"), 1200);
        auto dpiEdit = new NumberEdit;
        dpiEdit->setLabel(tr("DPI"));
        dpiEdit->setRange(1, 100000);
        dpiEdit->setDecimals(0);
        _dpi = prefs->getInt(dpi_pref, _dpi);
        dpiEdit->setValue(_dpi);
        if (dpiSelector->setActiveById(_dpi)) {
            dpiSelector->setPlaceholderText("Select...");
        }
        dpiSelector->addPopupWidget(dpiEdit, 0);

        connect(dpiSelector, &IconComboBox::currentChanged, this, [this, prefs, dpiEdit](int id) {
            if (id < 0) return; // selection cleared for a custom value
            _dpi = id;
            prefs->setInt(dpi_pref, _dpi);
            const QSignalBlocker blocker(dpiEdit);
            dpiEdit->setValue(id);
        });
        connect(dpiEdit, &NumberEdit::valueChanged, this, [this, prefs, dpiSelector](double value) {
            _dpi = static_cast<int>(value);
            prefs->setInt(dpi_pref, _dpi);
            // highlight the matching preset, or clear the highlight for a custom value
            if (!dpiSelector->setActiveById(_dpi)) {
                dpiSelector->setActiveById(-1);
                dpiSelector->setPlaceholderText(QString::number(_dpi) + " DPI");
            }
            else {
                dpiSelector->setPlaceholderText("Select...");
            }
        });

        _extensionSelector = new ExtensionSelector(this);
        _extensionSelector->setToolTip(tr("Choose the export type"));

        auto optionsButton = new QPushButton(this);
        optionsButton->setIcon(QIcon(":/icons/gear"));
        optionsButton->setToolTip(tr("Export options"));

        auto removeButton = new QPushButton(this);
        removeButton->setIcon(QIcon(":/icons/minus"));
        removeButton->setToolTip(tr("Remove export task"));
        connect(removeButton, &QPushButton::clicked, this, [this] {
            if (_removeHandler) {
                _removeHandler();
            }
        });

        layout->addWidget(dpiSelector, 0, 0);
        layout->addWidget(_extensionSelector, 0, 1);
        layout->addWidget(optionsButton, 0, 2);
        layout->addWidget(removeButton, 0, 3);
        layout->setColumnStretch(0, 1);
        layout->setColumnStretch(1, 1);

        connect(optionsButton, &QPushButton::clicked, this, [this, optionsButton] {
            showOptions(optionsButton);
        });
    }

    void setRemoveHandler(std::function<void()> handler) {
        _removeHandler = std::move(handler);
    }

    int dpi() const { return _dpi; }

    Inkscape::Extension::Output* selectedExtension() const {
        return _extensionSelector->selectedExtension();
    }

private:
    void showOptions(QPushButton* button) {
        auto extension = selectedExtension();
        if (!extension) {
            return;
        }

        delete _optionsPopup;
        _optionsPopup = new PopupMenu(this);
        auto options = extension->autogui(nullptr, nullptr);
        if (!options) {
            delete _optionsPopup;
            _optionsPopup = nullptr;
            return;
        }

        _optionsPopup->setContent(options);
        _optionsPopup->showBelowWidget(button);
    }

    ExtensionSelector* _extensionSelector = nullptr;
    std::function<void()> _removeHandler;
    PopupMenu* _optionsPopup = nullptr;
    int _dpi = 96;
};

