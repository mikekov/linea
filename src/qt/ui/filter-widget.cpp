// Matches the BLUR_MULTIPLIER used in filter-chemistry.cpp and the GTK panel.
constexpr double BLUR_MULTIPLIER = 4.0;

/// Apply a filter to the item and record undo. The apply callback is run
/// under an update block so the subsequent refresh doesn't re-enter the widget.
void applyFilterAndUndo(SPItem* spitem, OperationBlocker& update,
                        std::function<void()> apply) {
    auto scoped = update.block();
    apply();
    DocumentUndo::done(spitem->document, RC_("Undo", "Add filter"), INKSCAPE_ICON("dialog-filters"));
}

/// Look up an extension effect by ID. Returns nullptr if not found or not an Effect.
Inkscape::Extension::Effect* lookupEffect(const QString& id) {
    if (id.isEmpty()) return nullptr;

    auto ext = Inkscape::Extension::db.get(id.toUtf8().constData());
    return dynamic_cast<Inkscape::Extension::Effect*>(ext);
}

/// Populate a tree item as an extension filter leaf: display name (with a
/// trailing "..." when the effect takes parameters), the effect's ID in
/// UserRole, and -1 in UserRole+1 to mark it as an extension (not built-in).
void setExtensionLeaf(QTreeWidgetItem* item, Inkscape::Extension::Effect* effect) {
    if (!item || !effect) return;

    auto name = QString::fromUtf8(effect->get_name());
    if (effect->takes_input()) {
        name += QString::fromUtf8(_("..."));
    }
    item->setText(0, name);
    item->setData(0, Qt::UserRole, QString::fromUtf8(effect->get_id()));
    item->setData(0, Qt::UserRole + 1, -1); // marks extension (not built-in)
}

/// Create a new filter with the given primitive type and attach it to the item.
/// For Gaussian blur, use the blur-specific helper that computes radius from
/// a percentage of the bounding box; for all others, create a fresh filter
/// with a single primitive.
void add_filter_to_item(SPItem* item, Filters::FilterPrimitiveType type) {
    if (!item || !item->document) return;

    if (type == Filters::NR_FILTER_GAUSSIANBLUR) {
        // Default to 10% blur, matching the GTK "add blur" button.
        modify_filter_gaussian_blur_amount(item, 10.0);
        return;
    }

    auto filter = new_filter(item->document);
    filter_add_primitive(filter, type);
    sp_style_set_property_url(item, "filter", filter, false);
    item->updateRepr(SP_OBJECT_MODIFIED_FLAG | SP_OBJECT_STYLE_MODIFIED_FLAG);
}

/// Information about the filter currently attached to an object, for display.
struct FilterDisplayInfo {
    size_t count = 0;
    bool is_gaussian_blur = false;
    double blur_percent = 0.0;
    QString label;
};

FilterDisplayInfo get_filter_display_info(SPObject* object) {
    FilterDisplayInfo info;

    auto item = cast<SPItem>(object);
    if (!item) return info;

    info.count = get_filter_primitive_count(object);
    if (info.count == 0) return info;

    if (info.count == 1) {
        auto primitive = get_first_filter_component(object);
        if (primitive && primitive->getRepr()) {
            auto id = FPConverter.get_id_from_key(primitive->getRepr()->name());
            info.label = QString::fromUtf8(_(FPConverter.get_label(id).c_str()));
            if (id == Filters::NR_FILTER_GAUSSIANBLUR) {
                info.is_gaussian_blur = true;
                if (auto radius = object_query_blur_filter(item)) {
                    if (auto bbox = item->desktopGeometricBounds()) {
                        double perimeter = bbox->dimensions()[Geom::X] + bbox->dimensions()[Geom::Y];
                        if (perimeter > 0) {
                            info.blur_percent = std::sqrt(*radius * BLUR_MULTIPLIER / perimeter) * 100.0;
                        }
                    }
                }
            }
        }
    } else {
        // Without a reliable way to distinguish a single extension filter from
        // a merged/compound one, always use the generic label.
        info.label = QString::fromUtf8(_("Compound filter"));
    }

    return info;
}

