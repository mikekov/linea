void FilterWidget::onAddButtonClicked() {
    if (!_object) return;

    if (!_addPopup) {
        _addPopup = new PopupMenu(this);

        auto content = new QWidget();
        auto contentLayout = new QVBoxLayout(content);
        contentLayout->setContentsMargins(0, 0, 0, 0);
        contentLayout->setSpacing(4);

        _searchEdit = new QLineEdit(content);
        _searchEdit->setPlaceholderText(QString::fromUtf8(_("Search...")));
        contentLayout->addWidget(_searchEdit);

        _addList = new QTreeWidget(content);
        _addList->setFixedSize(240, 280);
        _addList->setHeaderHidden(true);
        _addList->setRootIsDecorated(true);
        _addList->setExpandsOnDoubleClick(false);
        _addList->setUniformRowHeights(true);
        _addList->setFocusPolicy(Qt::NoFocus); // keep focus on the search edit
        contentLayout->addWidget(_addList);

        connect(_searchEdit, &QLineEdit::textChanged, this, &FilterWidget::onSearchChanged);

        // Single click: expand/collapse categories, apply leaves.
        connect(_addList, &QTreeWidget::itemClicked, this, [this](QTreeWidgetItem* item) {
            if (!item) return;
            if (item->childCount() > 0) {
                item->setExpanded(!item->isExpanded());
            } else {
                applyTreeItem(item);
                _addPopup->hide();
            }
        });

        // Keyboard navigation: while the search box has focus, arrow keys
        // drive the tree selection and Enter applies the selected filter.
        _searchEdit->installEventFilter(this);

        _addPopup->setContent(content);

        populateAddPopup();
    }

    _addPopup->showLeftOfWidget(_ui->addButton);
    _searchEdit->clear();
    _searchEdit->setFocus();
}

void FilterWidget::populateAddPopup() {
    if (!_addList) return;
    _addList->clear();

    // Extension filters, organized into categories by get_menu_list() path.
    std::map<QString, QTreeWidgetItem*> categoryNodes;

    for (auto effect : Inkscape::Extension::db.get_effect_list()) {
        if (!effect->is_filter_effect()) continue;
        if (effect->hidden_from_menu()) continue;

        auto parent = _addList->invisibleRootItem();
        const auto& menuList = effect->get_menu_list();
        QString path;

        for (auto const& submenu : menuList) {
            auto name = QString::fromUtf8(submenu.c_str());
            path += "/" + name;

            auto it = categoryNodes.find(path);
            if (it == categoryNodes.end()) {
                auto node = new QTreeWidgetItem(parent);
                node->setText(0, name);
                categoryNodes[path] = node;
                parent = node;
            } else {
                parent = it->second;
            }
        }

        auto leaf = new QTreeWidgetItem(parent);
        setExtensionLeaf(leaf, effect);
    }

    _addList->sortByColumn(0, Qt::AscendingOrder);

    // Built-in Gaussian blur pinned at the top, above the sorted extension
    // categories. Inserted after the sort so it stays at index 0 and is not
    // reshuffled into its alphabetical position. Special-cased with a
    // percentage-based SpinScale UI.
    auto builtin = new QTreeWidgetItem();
    builtin->setText(0, QString::fromUtf8(_(FPConverter.get_label(Filters::NR_FILTER_GAUSSIANBLUR).c_str())));
    builtin->setData(0, Qt::UserRole, QString()); // empty ID marks built-in
    builtin->setData(0, Qt::UserRole + 1, static_cast<int>(Filters::NR_FILTER_GAUSSIANBLUR));
    _addList->insertTopLevelItem(0, builtin);
}

void FilterWidget::onSearchChanged() {
    if (!_addList) return;
    QString text = _searchEdit->text().toLower();

    for (int i = 0; i < _addList->topLevelItemCount(); ++i) {
        filterTreeItem(_addList->topLevelItem(i), text);
    }

    // Select the first visible leaf so Enter works right after filtering.
    auto first = Linea::UI::firstVisibleLeaf(_addList);
    if (first) {
        _addList->setCurrentItem(first);
    }
}

bool FilterWidget::filterTreeItem(QTreeWidgetItem* item, const QString& text) {
    bool isLeaf = item->childCount() == 0;

    if (isLeaf) {
        bool match = text.isEmpty() || item->text(0).toLower().contains(text);
        item->setHidden(!match);
        return match;
    }

    // Category: visible if any descendant matches.
    bool anyVisible = false;
    for (int i = 0; i < item->childCount(); ++i) {
        if (filterTreeItem(item->child(i), text)) {
            anyVisible = true;
        }
    }
    item->setHidden(!anyVisible);
    // Auto-expand categories while searching; collapse when search is cleared.
    item->setExpanded(anyVisible && !text.isEmpty());
    return anyVisible;
}

void FilterWidget::applyTreeItem(QTreeWidgetItem* item) {
    if (!item || item->childCount() > 0) return; // only leaves

    auto spitem = cast<SPItem>(_object);
    if (!spitem) return;

    auto id = item->data(0, Qt::UserRole).toString();

    if (id.isEmpty()) {
        // Built-in primitive (e.g. Gaussian blur).
        int typeInt = item->data(0, Qt::UserRole + 1).toInt();
        auto type = static_cast<Filters::FilterPrimitiveType>(typeInt);
        applyFilterAndUndo(spitem, _update, [&] { add_filter_to_item(spitem, type); });
        refreshFilters();
        return;
    }

    applyEffect(id);
}

void FilterWidget::applyEffect(const QString& id) {
    auto spitem = cast<SPItem>(_object);
    if (!spitem) return;

    auto effect = lookupEffect(id);
    if (!effect) return;

    if (effect->takes_input()) {
        // Effects with parameters: show pref dialog immediately.
        // The dialog applies the filter via effect() when the user
        // clicks Apply, and handles its own undo.
        if (_addPopup) {
            _addPopup->hide();
        }
        if (_galleryPopup) {
            _galleryPopup->hide();
        }
        effect->prefs(_desktop);
        refreshFilters();
        return;
    }

    // No parameters: apply immediately.
    applyFilterAndUndo(spitem, _update, [&] { effect->apply_filter(spitem); });
    refreshFilters();
}

void FilterWidget::removeCurrentFilter() {
    if (!_object) return;

    auto scoped = _update.block();
    remove_filter(_object, false);
    DocumentUndo::done(_object->document, RC_("Undo", "Remove filter"), INKSCAPE_ICON("dialog-filters"));
    refreshFilters();
}

