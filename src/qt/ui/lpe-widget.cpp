/// Apply an LPE of the given type to the item.
void apply_lpeffect(SPItem* item, LivePathEffect::EffectType type) {
    if (!item) return;
    auto key = LivePathEffect::LPETypeConverter.get_key(type);
    LivePathEffect::Effect::createAndApply(key.c_str(), item->document, item);
    DocumentUndo::done(item->document, RC_("Undo", "Create and apply path effect"),
                       INKSCAPE_ICON("dialog-path-effects"));
}

/// Remove the LPE at the given index from the object.
void remove_lpeffect(SPObject* object, int index) {
    auto lpe_item = cast<SPLPEItem>(object);
    if (!lpe_item || !lpe_item->path_effect_list) return;

    int i = 0;
    for (auto&& lpe : *lpe_item->path_effect_list) {
        if (index == i) {
            if (auto effect = lpe->lpeobject ? lpe->lpeobject->get_lpe() : nullptr) {
                lpe_item->removePathEffect(effect, false);
                DocumentUndo::done(object->document, RC_("Undo", "Removed live path effect"),
                                   INKSCAPE_ICON("dialog-path-effects"));
            }
            break;
        }
        i++;
    }
}

/// Get the list of applied LPEs as (effect, index) pairs.
std::vector<std::pair<LivePathEffect::Effect*, int>> get_applied_lpes(SPObject* object) {
    std::vector<std::pair<LivePathEffect::Effect*, int>> result;
    auto lpe_item = cast<SPLPEItem>(object);
    if (!lpe_item || !lpe_item->path_effect_list) return result;

    int index = 0;
    for (auto&& lpe : *lpe_item->path_effect_list) {
        if (auto effect = lpe->lpeobject ? lpe->lpeobject->get_lpe() : nullptr) {
            result.emplace_back(effect, index);
        }
        index++;
    }
    return result;
}

/// Get the PathEffectSharedPtr at the given index, or nullptr.
PathEffectSharedPtr get_lperef_at_index(SPObject* object, int index) {
    auto lpe_item = cast<SPLPEItem>(object);
    if (!lpe_item || !lpe_item->path_effect_list) return nullptr;

    int i = 0;
    for (auto&& lpe : *lpe_item->path_effect_list) {
        if (i == index) {
            return lpe;
        }
        i++;
    }
    return nullptr;
}

/// Get the Effect at the given index, or nullptr.
LivePathEffect::Effect* get_effect_at_index(SPObject* object, int index) {
    auto lperef = get_lperef_at_index(object, index);
    return lperef && lperef->lpeobject ? lperef->lpeobject->get_lpe() : nullptr;
}

